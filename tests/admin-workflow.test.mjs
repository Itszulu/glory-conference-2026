import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const file=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const app=file('src/App.jsx')
const staff=file('src/StaffManagement.jsx')
const navigation=file('src/AdminNavigation.jsx')
const registration=file('src/RegistrationDesk.jsx')
const attendance=file('src/AttendanceDesk.jsx')
const rules=file('firestore.rules')
const backend=file('functions/index.js')
test('each operational role lands on only its dedicated workspace',()=>{
 assert.match(app,/role==='registration'\?'registration-desk':'attendance'/)
 assert.match(app,/staffRole==='registration'\)\&\&tab==='registration-desk'/)
 assert.match(app,/staffRole==='checkin'\)\&\&tab==='attendance'/)
 assert.match(app,/tab==='overview'/)
 assert.match(app,/tab==='staff'&&<StaffManagement user=\{user\}/)
 assert.match(navigation,/registration:\['registration-desk'\]/)
 assert.match(navigation,/checkin:\['attendance'\]/)
 assert.match(navigation,/followup:\['follow-up'\]/)
 assert.match(navigation,/MINISTRY & TEAM/)
})
test('registration officers collect titles and only register attendees',()=>{
 assert.match(registration,/MINISTRY TITLE \(OPTIONAL\)/)
 assert.match(registration,/\['Pastor','Reverend','Prophet','Bishop','Apostle','Minister','Evangelist'\]/)
 assert.match(registration,/attendeeRegistrationId/)
 assert.match(registration,/runTransaction/)
 assert.match(registration,/followUpConsent:form.followUpConsent/)
 assert.doesNotMatch(registration,/checkIns|checkedInAt|checkedOutAt/)
})
test('attendance desk checks in and out registered guests with actor timestamps',()=>{
 assert.match(attendance,/checkedInAt:serverTimestamp\(\)/)
 assert.match(attendance,/checkedInBy:user.uid/)
 assert.match(attendance,/checkedOutAt:serverTimestamp\(\)/)
 assert.match(attendance,/checkedOutBy:user.uid/)
 assert.match(attendance,/runTransaction/)
 assert.doesNotMatch(attendance,/setDoc\(doc\(db,'registrations'/)
})
test('staff creation and disable require server-side administrator verification',()=>{
 assert.match(staff,/httpsCallable\(callable\(\),'createStaffAccount'\)/)
 assert.match(staff,/httpsCallable\(callable\(\),'revokeStaffAccount'\)/)
 assert.match(backend,/requireSuperAdmin\(request\)/)
 assert.match(backend,/auth\.createUser/)
 assert.match(backend,/auth\.generatePasswordResetLink/)
 assert.match(backend,/auth\.updateUser\(uid,\{disabled:true\}\)/)
 assert.match(backend,/role!=='admin'/) // no admin role in provisioner
 assert.doesNotMatch(staff,/createUserWithEmailAndPassword|privateKey/)
})
test('Firestore separates registration and attendance writes and protects checkout',()=>{
 assert.match(rules,/function isCheckInStaff\(\) \{ return staffRole\(\) in \['admin','checkin'\]; \}/)
 assert.match(rules,/function isRegistrationStaff\(\) \{ return staffRole\(\) in \['admin','registration'\]; \}/)
 assert.match(rules,/allow read: if isRegistrationStaff\(\) \|\| isCheckInStaff\(\) \|\| isFollowUpStaff\(\)/)
 assert.match(rules,/!\('checkedOutAt' in resource.data\)/)
 assert.match(rules,/checkedOutAt == request.time/)
 assert.match(rules,/checkedOutBy == request.auth.uid/)
 assert.match(rules,/allow list: if isAdmin\(\)/)
})
