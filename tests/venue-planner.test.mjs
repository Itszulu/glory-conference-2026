import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const app=readFileSync(new URL('../src/App.jsx',import.meta.url),'utf8')
const venue=readFileSync(new URL('../src/VenueDirections.jsx',import.meta.url),'utf8')
const venueConfig=readFileSync(new URL('../src/conferenceVenue.js',import.meta.url),'utf8')
const css=readFileSync(new URL('../src/venue.css',import.meta.url),'utf8')
const layout=readFileSync(new URL('../src/layout-fix.css',import.meta.url),'utf8')
const main=readFileSync(new URL('../src/main.jsx',import.meta.url),'utf8')

test('homepage never renders the journey planner',()=>{
  const home=app.slice(app.indexOf('function Home()'),app.indexOf('function MinisterCards()'))
  assert.ok(home.startsWith('function Home(){'))
  assert.ok(home.includes('<Header/>'))
  assert.ok(home.includes('<Footer/>'))
  assert.doesNotMatch(home,/<VenueDirections\b/)
  assert.match(app,/function Directions\(\)\{return <Shell/)
  assert.match(app,/'\/directions':Directions/)
  assert.match(venue,/href="\/directions"/)
})
test('existing homepage styling keeps the original hero first',()=>{
  assert.match(layout,/body>div>main:has\(> \.hero\) > \.hero\{order:1!important\}/)
  assert.doesNotMatch(layout,/body>div>main:has\(> \.hero\) > \.gc-venue/)
})
test('Google-powered direction page uses a real selected Places result and computed Routes data',()=>{
  assert.match(venue,/VITE_GOOGLE_MAPS_API_KEY/)
  assert.match(venue,/maps\.googleapis\.com\/maps\/api\/js/)
  assert.match(venue,/PlaceAutocompleteElement/)
  assert.match(venue,/gmp-select/)
  assert.match(venue,/place\.fetchFields/)
  assert.match(venue,/place\.location/)
  assert.match(venue,/includedRegionCodes=\['ng'\]/)
  assert.match(venue,/Route\.computeRoutes\(request\)/)
  assert.match(venue,/route\.createPolylines\(\)/)
  assert.match(venue,/route\.durationMillis/)
  assert.match(venue,/route\.distanceMeters/)
  assert.match(venue,/TRAFFIC_AWARE/)
  assert.match(venue,/Divine Intervention Soul Rescue Ministry/)
  assert.match(venue,/conferenceVenue\.latitude/)
  assert.match(venue,/conferenceVenue\.longitude/)
  assert.doesNotMatch(venue,/Ikenga Hotel|landmarkLatitude|landmarkLongitude/)
  assert.match(venueConfig,/latitude:6\.836262173294491/)
  assert.match(venueConfig,/longitude:7\.370666488580394/)
  assert.doesNotMatch(venueConfig,/Ikenga Hotel/)
  assert.doesNotMatch(venue,/api\.heigit\.org|pelias\/v1|VITE_ORS_API_KEY/)
  assert.match(css,/gc-google-origin/)
})
test('polished journey planner preserves Google search and real route interactions',()=>{
  assert.match(venue,/className="gc-route-panel"/)
  assert.match(venue,/className="gc-route-destination"/)
  assert.match(venue,/CarFront/)
  assert.match(venue,/Footprints/)
  assert.match(venue,/GET MY DIRECTIONS/)
  assert.match(venue,/className="gc-venue-map-bottom"/)
  assert.match(css,/\.gc-route-panel \.gc-journey-modes button\.selected/)
  assert.match(css,/\.gc-route-panel \.gc-google-origin:focus-within/)
  assert.match(css,/@media\(max-width:560px\)/)
  assert.match(venue,/Route\.computeRoutes\(request\)/)
})
test('Google Places owns an empty host node and cannot remove React-owned loading text',()=>{
  assert.match(venue,/<div ref=\{placeWidgetHost\}[^>]*\/>/)
  assert.match(venue,/placeWidgetHost\.current\.appendChild\(widget\)/)
  assert.doesNotMatch(venue,/replaceChildren\(/)
  assert.match(venue,/disposed=true/)
  assert.match(venue,/if\(disposed\|\|!activeRef\.current\)return/)
  assert.doesNotMatch(venue,/new maps\.Marker\(/)
})
test('desktop navigation, desktop hero and hamburger all link to directions',()=>{
  assert.match(app,/<a className="gc-desktop-venue-link" href="\/directions">DIRECTIONS<\/a>/)
  assert.match(app,/<a className="button ghost gc-hero-directions" href="\/directions">GET DIRECTIONS/)
  assert.match(app,/href="\/directions" onClick=\{\(\)=>setOpen\(false\)\}/)
  assert.match(css,/\.nav-links \.gc-desktop-venue-link/)
  assert.match(css,/\.hero \.actions \.gc-hero-directions/)
})
test('runtime sharing URLs still refer to live website',()=>{
  assert.doesNotMatch(main,/gloryconf\.org/)
  assert.match(main,/gloryconf\.web\.app/)
})
